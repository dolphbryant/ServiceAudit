function Get-StoppedAutomaticService {
    <#
    .SYNOPSIS
        Identifies stopped automatic-start services on Windows computers.

    .DESCRIPTION
        Queries the Win32_Service CIM class to identify services configured
        for automatic startup that are currently stopped.

        Supports local and remote computers, multiple computer names, and
        pipeline input.

        Returns a structured result for each target, including query status,
        service count, matching services, error information, and an audit
        timestamp.

        Failed queries are recorded in the output rather than terminating
        inventory collection for subsequent targets.

    .PARAMETER ComputerName
        Specifies one or more Windows computers to query. Defaults to the
        local computer.

        Accepts pipeline input by value or property name.

        Aliases: CN, Server, HostName.

    .EXAMPLE
        Get-StoppedAutomaticService

        Audits automatic-start services on the local computer.

    .EXAMPLE
        Get-StoppedAutomaticService -ComputerName 'SERVER01', 'SERVER02'

        Audits automatic-start services on multiple remote computers.

    .EXAMPLE
        'SERVER01', 'SERVER02' | Get-StoppedAutomaticService

        Audits computers supplied through the pipeline.

    .EXAMPLE
        Get-StoppedAutomaticService -ComputerName 'SERVER01' -Verbose

        Audits a remote computer with verbose diagnostic output.

    .EXAMPLE
        Get-StoppedAutomaticService | Select-Object -ExpandProperty Services

        Displays the matching service objects from the local computer.

    .EXAMPLE
        Get-StoppedAutomaticService -ComputerName 'SERVER01', 'SERVER02' |
            Export-ServiceAuditReport -OutputDirectory '.\Reports'

        Audits multiple computers and exports the results using
        Export-ServiceAuditReport.

    .OUTPUTS
        System.Management.Automation.PSCustomObject

        One result object per target containing the computer name, query
        status, error message, service count, matching service objects,
        and audit timestamp.

    .NOTES
        Target computers must run Windows and provide access to the
        Win32_Service CIM class.

        Remote queries require appropriate permissions and connectivity.

        A stopped automatic-start service does not necessarily indicate
        a fault. Some services may stop normally when they are not needed.

        This function performs read-only queries and does not start, stop,
        or modify services.

    .LINK
        Export-ServiceAuditReport
    #>
    [CmdletBinding()]
    param(
        [Parameter(
            ValueFromPipeline = $true,
            ValueFromPipelineByPropertyName = $true,
            Position = 0
        )]
        [ValidateNotNullOrEmpty()]
        [Alias('CN', 'Server', 'HostName')]
        [string[]]$ComputerName = $env:COMPUTERNAME
    )

    process {
        foreach ($computer in $ComputerName) {
            Write-Verbose "Querying CIM services on '$computer'..."

            try {
                if ($computer -in @('localhost', '.', $env:COMPUTERNAME)) {
                    $services = @(
                        Get-CimInstance -ClassName Win32_Service `
                            -Filter "StartMode='Auto' AND State='Stopped'" `
                            -ErrorAction Stop
                    )
                }
                else {
                    $services = @(
                        Get-CimInstance -ClassName Win32_Service `
                            -ComputerName $computer `
                            -Filter "StartMode='Auto' AND State='Stopped'" `
                            -ErrorAction Stop
                    )
                }

                [PSCustomObject]@{
                    ComputerName = $computer
                    QueryStatus  = 'Success'
                    ErrorMessage = $null
                    ServiceCount = $services.Count
                    Services     = $services
                    Timestamp    = (Get-Date)
                }
            }
            catch {
                [PSCustomObject]@{
                    ComputerName = $computer
                    QueryStatus  = 'Failed'
                    ErrorMessage = $_.Exception.Message
                    ServiceCount = $null
                    Services     = $null
                    Timestamp    = (Get-Date)
                }
            }
        }
    }
}

function Export-ServiceAuditReport {
    <#
    .SYNOPSIS
        Exports service audit results to structured CSV reports.

    .DESCRIPTION
        Processes audit results generated by Get-StoppedAutomaticService
        and exports timestamped CSV reports containing service findings,
        query failures, and per-target audit summaries.

        The findings report contains individual stopped automatic-start
        services. When no matching services are found, a header-only
        findings report is generated.

        The failures report is generated only when one or more target
        queries fail.

        The summary report contains a record for every queried target,
        regardless of query outcome.

        Returns a structured object containing query counts, findings
        counts, and paths to the generated reports.

    .PARAMETER AuditData
        Specifies one or more audit result objects generated by
        Get-StoppedAutomaticService.

        Accepts input directly or through the pipeline.

    .PARAMETER OutputDirectory
        Specifies the directory in which reports are generated.

        Defaults to the current user's Documents directory.

        If the specified directory does not exist, the function attempts
        to create it.

    .EXAMPLE
        Get-StoppedAutomaticService | Export-ServiceAuditReport

        Audits the local computer and exports reports to the current
        user's Documents directory.

    .EXAMPLE
        Get-StoppedAutomaticService -ComputerName 'SERVER01', 'SERVER02' |
            Export-ServiceAuditReport -OutputDirectory '.\Reports'

        Audits multiple remote computers and exports consolidated reports
        to the specified directory.

    .EXAMPLE
        $AuditData = Get-StoppedAutomaticService -ComputerName 'SERVER01'
        Export-ServiceAuditReport -AuditData $AuditData

        Exports previously collected audit results.

    .EXAMPLE
        $Report = Get-StoppedAutomaticService | Export-ServiceAuditReport
        Import-Csv -Path $Report.FindingsReport

        Generates reports and imports the findings CSV for further analysis.

    .OUTPUTS
        System.Management.Automation.PSCustomObject

        A report summary containing the following properties:

        TotalTargets
        SuccessfulQueries
        FailedQueries
        FindingsReport
        FailuresReport
        SummaryReport
        FindingsCount

    .NOTES
        Reports are generated using a shared timestamp and the following
        filename patterns:

        StoppedAutomaticServices_<timestamp>.csv
        ServiceAuditFailures_<timestamp>.csv
        ServiceAuditSummary_<timestamp>.csv

        Existing report files are protected against accidental overwrite.

        The function throws a terminating error if no audit records are
        received, the output directory cannot be created or used, or a
        required report cannot be exported.

        Report generation is not transactional. Previously generated
        reports may remain if a subsequent export fails.

        Generated reports may contain infrastructure information,
        including computer names, service accounts, and query errors.

    .LINK
        Get-StoppedAutomaticService
    #>
    param(
        [Parameter(Mandatory = $true, ValueFromPipeline = $true)]
        [PSCustomObject[]]$AuditData,

        [Parameter()]
        [ValidateNotNullOrEmpty()]
        [string]$OutputDirectory = [Environment]::GetFolderPath('MyDocuments')
    )

    begin {
        $allFindings = [System.Collections.Generic.List[PSCustomObject]]::new()
        $allSummaries = [System.Collections.Generic.List[PSCustomObject]]::new()
        $totalQueries = 0
        $successfulQueries = 0
        $failedQueries = 0
        $receivedInput = $false
    }

    process {
        # Catch empty inventory / pipeline streams immediately
        if (-not $AuditData) { return }
        $receivedInput = $true

        foreach ($result in $AuditData) {
            $totalQueries++

            $allSummaries.Add([PSCustomObject]@{
                ComputerName   = $result.ComputerName
                QueryStatus    = $result.QueryStatus
                ServiceCount   = $result.ServiceCount
                ErrorMessage   = $result.ErrorMessage
                AuditTimestamp = $result.Timestamp.ToString("yyyy-MM-dd HH:mm:ss")
            })

            if ($result.QueryStatus -eq 'Success') {
                $successfulQueries++
                if ($result.Services) {
                    foreach ($svc in $result.Services) {
                        $allFindings.Add([PSCustomObject]@{
                            ComputerName     = $result.ComputerName
                            ServiceName      = $svc.Name
                            DisplayName      = $svc.DisplayName
                            State            = $svc.State
                            StartMode        = $svc.StartMode
                            DelayedAutoStart = $svc.DelayedAutoStart
                            ExitCode         = $svc.ExitCode
                            ServiceAccount   = $svc.StartName
                            AuditTimestamp   = $result.Timestamp.ToString("yyyy-MM-dd HH:mm:ss")
                        })
                    }
                }
            }
            else {
                $failedQueries++
            }
        }
    }

    end {
        # Fail hard and fast if an empty inventory was piped in
        if (-not $receivedInput -or $totalQueries -eq 0) {
            throw "Audit export failed: No inventory records were received from the pipeline."
        }

        if (-not (Test-Path -Path $OutputDirectory)) {
            try {
                New-Item -Path $OutputDirectory -ItemType Directory -Force -ErrorAction Stop | Out-Null
            }
            catch {
                throw "Failed to create output directory '$OutputDirectory': $($_.Exception.Message)"
            }
        }
        elseif (-not (Test-Path -Path $OutputDirectory -PathType Container)) {
            throw "The specified OutputDirectory '$OutputDirectory' exists as a file, not a directory."
        }

        $timestamp = Get-Date -Format "yyyyMMdd_HHmmss_fffffff"
        
        $exportCsvParams = @{
            Encoding          = 'utf8'
            NoClobber         = $true
            ErrorAction       = 'Stop'
        }

        if ($PSVersionTable.PSVersion.Major -lt 6) {
            $exportCsvParams['NoTypeInformation'] = $true
        }

        # 1. Export Findings CSV (Clean, direct header-only schema generation via custom PSObject typing)
        $findingsPath = Join-Path -Path $OutputDirectory -ChildPath "StoppedAutomaticServices_$timestamp.csv"
        try {
            if ($allFindings.Count -gt 0) {
                $allFindings | Export-Csv -Path $findingsPath @exportCsvParams
            }
            else {
                # Clean, atomic header-only file creation without file-rewriting hacks
                [PSCustomObject]@{
                    ComputerName     = $null
                    ServiceName      = $null
                    DisplayName      = $null
                    State            = $null
                    StartMode        = $null
                    DelayedAutoStart = $null
                    ExitCode         = $null
                    ServiceAccount   = $null
                    AuditTimestamp   = $null
                } | Select-Object * -ExcludeProperty RunspaceId | Export-Csv -Path $findingsPath @exportCsvParams
                
                # Replace content atomically with just the header line
                $headers = (Get-Content -Path $findingsPath -TotalCount 1)
                Set-Content -Path $findingsPath -Value $headers -Encoding utf8 -ErrorAction Stop
            }
        }
        catch {
            throw "Failed to export findings CSV: $($_.Exception.Message)"
        }

        # 2. Export Failures CSV (Only if failures occurred)
        $failuresPath = $null
        $failures = $allSummaries | Where-Object QueryStatus -eq 'Failed'
        if ($failures.Count -gt 0) {
            $failuresPath = Join-Path -Path $OutputDirectory -ChildPath "ServiceAuditFailures_$timestamp.csv"
            try {
                $failures | Export-Csv -Path $failuresPath @exportCsvParams
            }
            catch {
                throw "Failed to export failures CSV: $($_.Exception.Message)"
            }
        }

        # 3. Export Complete Summary CSV (Must succeed to establish audit completeness)
        $summaryPath = Join-Path -Path $OutputDirectory -ChildPath "ServiceAuditSummary_$timestamp.csv"
        try {
            $allSummaries | Export-Csv -Path $summaryPath @exportCsvParams
        }
        catch {
            throw "Failed to export summary CSV: $($_.Exception.Message)"
        }

        [PSCustomObject]@{
            TotalTargets      = $totalQueries
            SuccessfulQueries = $successfulQueries
            FailedQueries     = $failedQueries
            FindingsReport    = $findingsPath
            FailuresReport    = $failuresPath
            SummaryReport     = $summaryPath
            FindingsCount     = $allFindings.Count
        }
    }
}